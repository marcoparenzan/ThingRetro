using System.Text;

namespace Thing65.Graphics;

// The files of a graphics asset, written next to its .gfx.json: one name.part.bin per part, and name.inc.asm, which
// defines the constants and a label on each part:
//   TITLE_BACKGROUND = 0
//   * = $2000                                 (only when the asset gives the part an address)
//   title_bitmap:   !binary "title.bitmap.bin"
// A source includes it with !source "gfx/title.inc.asm"
public static class GraphicsBuilder
{
    public sealed record Result(Conversion Conversion, IReadOnlyList<string> Files);

    public static Result Build(string assetPath)
    {
        var asset = GraphicsAsset.Load(assetPath);
        string folder = Path.GetDirectoryName(Path.GetFullPath(assetPath))!;
        if (asset.Source.Length == 0) throw new InvalidDataException($"{Path.GetFileName(assetPath)}: no \"source\" image");
        var image = Png.Read(File.ReadAllBytes(Path.Combine(folder, asset.Source)));
        var conversion = Converter.Convert(image, asset);

        string name = asset.Name ?? GraphicsAsset.NameOf(assetPath);
        var files = new List<string>();
        foreach (var part in conversion.Parts)
        {
            string file = $"{name}.{part.Name}.bin";
            File.WriteAllBytes(Path.Combine(folder, file), part.Data);
            files.Add(file);
        }
        string include = asset.Include ?? name + ".inc.asm";
        File.WriteAllText(Path.Combine(folder, include), IncludeSource(name, Path.GetFileName(assetPath), asset, conversion));
        files.Add(include);
        return new Result(conversion, files);
    }

    public static string IncludeSource(string name, string assetFile, GraphicsAsset asset, Conversion conversion)
    {
        string label = Identifier(name).ToLowerInvariant();
        string constant = label.ToUpperInvariant();
        var text = new StringBuilder();
        text.AppendLine($"; {name} - generated by Thing65 from {assetFile} (and {asset.Source}): do not edit, it is rewritten at every build.");
        text.AppendLine($"; {conversion.Summary}");
        text.AppendLine();
        foreach (var (key, value) in conversion.Constants)
            text.AppendLine($"{constant}_{key,-16} = {value}");
        text.AppendLine();
        foreach (var part in conversion.Parts)
        {
            if (asset.Addresses.TryGetValue(part.Name, out var address)) text.AppendLine($"* = {address}");
            text.AppendLine($"; {part.Description}");
            text.AppendLine($"{label}_{part.Name}:".PadRight(24) + $"!binary \"{name}.{part.Name}.bin\"");
            text.AppendLine($"{label}_{part.Name}_end:");
        }
        return text.ToString();
    }

    // A name as an assembly symbol: letters, digits and underscores, not starting with a digit
    static string Identifier(string name)
    {
        var chars = name.Select(c => char.IsAsciiLetterOrDigit(c) ? c : '_').ToArray();
        string identifier = new string(chars).Trim('_');
        if (identifier.Length == 0) return "graphics";
        return char.IsAsciiDigit(identifier[0]) ? "g" + identifier : identifier;
    }

    // An image as a new asset: the defaults, the image as the source
    public static GraphicsAsset NewAsset(string imageFile) => new() { Source = imageFile };
}
